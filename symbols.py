def _market_lists() -> tuple[list[str], list[str]]:
    stars: list[str] = []
    main: list[str] = []
    for line in _ROWS.strip().splitlines():
        tokens = line.split()
        stars.extend(tokens[:5])
        main.extend(tokens[5:10])
    return stars, main


def get_bist_symbols() -> list[str]:
    """Yıldız + Ana Pazar birleşimini Yahoo Finance biçiminde döndürür."""
    stars, main = _market_lists()
    symbols = sorted(set(stars + main))
    return [f"{symbol}.IS" for symbol in symbols]


def get_market_counts() -> dict[str, int]:
    stars, main = _market_lists()
    return {
        "yildiz": len(set(stars)),
        "ana": len(set(main)),
        "toplam": len(set(stars + main)),
    }


